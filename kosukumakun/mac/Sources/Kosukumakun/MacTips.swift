/// 豆知識のあいだに はさむ、こすくまくんからの ひとこと。
///
/// こすくまくんは口が無いので、これも「思っているのが漏れている」もの。
/// **評価も命令もしない。** ずっと見ていた人が、ぽつりと言う感じ。
/// 後押しも入れるが、追い立てない言い方にしてある（「あと5ふんだけ」のように区切る）。
enum Cheers {

    static let seconds: CGFloat = 5.5

    /// ねぎらい
    static let praise: [String] = [
        "いつも がんばってて えらい",
        "ちゃんと やってるの みてたよ",
        "ここまで きたね",
        "きょうも よく やってる",
        "つづけてるの すごいと おもう",
        "できてる できてる",
        "ゆっくりでも すすんでる",
        "きょうの ぶんは じゅうぶん",
        "がんばってるの しってる",
        "すこし 進んだね",
        "いい かんじ",
        "えらいね",
    ]

    /// そっと背中を押す
    static let nudge: [String] = [
        "もう少し できるんじゃない？",
        "あと5ふん だけ がんばろう",
        "あと ひとつ だけ やってみる？",
        "もうひと息",
        "のこり すこし",
        "そのちょうし",
        "きりの いいところ まで",
        "ここまで やったら やすもう",
    ]

    /// 気づかい（追い立てるだけにならないように混ぜる）
    static let care: [String] = [
        "むりしすぎては だめだよ",
        "手が とまっても だいじょうぶ",
        "つかれたら やすんで いいよ",
        "せなか まるまってない？",
        "いきぬき も しごとのうち",
        "かたの ちから ぬいて",
        "みず のんだ？",
        "そとの あかるさ 見てみて",
        "まばたき してる？",
        "ためいき ついても いいよ",
    ]

    static func pick(avoiding recent: [String]) -> String {
        // ねぎらい → 後押し → 気づかい が だいたい均等に出るようにする
        let pool = [praise, nudge, care].randomElement() ?? praise
        let fresh = pool.filter { !recent.contains($0) }
        return (fresh.isEmpty ? pool : fresh).randomElement() ?? pool[0]
    }
}
